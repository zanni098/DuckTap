"""Dependency lockfiles for the generated Python CLI.

Every generated Python CLI depends on a small, fixed closure: Click, HTTPX,
Rich and their transitive requirements. This module renders two files next to
the generated ``pyproject.toml``:

* ``requirements.txt`` -- the direct dependencies, unpinned, for humans and
  ``pip install -r``.
* ``requirements.lock`` -- the same closure with every (transitive) package
  pinned to an exact version, so an install is reproducible.

Locking normally means asking a resolver (``pip-compile`` / ``pip freeze``),
which needs the network. ``press`` has to stay deterministic and offline, so by
default the lock is rendered from a curated, version-known pin set: the same
spec produces byte-identical output on every machine, CI included. Passing
``--lock-online`` opts in to resolving the pins for real; whenever that is
unavailable the curated set is used instead.
"""
from __future__ import annotations

import shutil
import subprocess
import tempfile
from pathlib import Path

# Direct dependencies of every generated Python CLI. Keep in sync with the
# generated ``pyproject.toml`` and with the pin set below.
DIRECT_DEPS: tuple[str, ...] = ("click>=8.1", "httpx>=0.27", "rich>=13.7")

_REQUIREMENTS_TXT_HEADER = (
    "# Generated by DuckTap: direct dependencies of this CLI.",
    "# For a fully pinned, reproducible install use requirements.lock:",
    "#   pip install -r requirements.lock",
    "",
)

_LOCK_HEADER = (
    "#",
    "# This file is generated by DuckTap.",
    "# It pins every dependency -- including transitive ones -- so that",
    "# `pip install -r requirements.lock` is reproducible.",
    "#",
    "# Regenerate against live PyPI with:",
    "#   ducktap press <spec> --lock-online   (requires pip-tools)",
    "#",
    "",
)

# Curated, known-good closure for the direct dependencies above. Environment
# markers keep the lock valid on every platform the generated CLI supports
# (``sys_platform``/``python_version`` markers are understood by pip).
KNOWN_PINS: tuple[str, ...] = (
    "anyio==4.8.0",
    "certifi==2024.8.30",
    "click==8.1.7",
    "h11==0.14.0",
    "httpcore==1.0.6",
    "httpx==0.27.2",
    "idna==3.10",
    "markdown-it-py==3.0.0",
    "mdurl==0.1.2",
    "pygments==2.18.0",
    "rich==13.9.4",
    "sniffio==1.3.1",
    "typing-extensions==4.12.2",
    'colorama==0.4.6 ; sys_platform == "win32"',
    'exceptiongroup==1.2.2 ; python_version < "3.11"',
)


def render_requirements_txt() -> str:
    """The direct dependencies, unpinned, for ``pip install -r``."""
    lines = [*_REQUIREMENTS_TXT_HEADER, *DIRECT_DEPS, ""]
    return "\n".join(lines)


def render_requirements_lock() -> str:
    """A deterministic, fully pinned lockfile for the dependency closure."""
    lines = [*_LOCK_HEADER, *KNOWN_PINS, ""]
    return "\n".join(lines)


def resolve_lock_with_pip_tools(*, timeout: int = 180) -> str | None:
    """Resolve the direct deps to pinned versions with ``pip-compile``.

    Returns the rendered lockfile text, or ``None`` when ``pip-compile`` is
    missing or the resolution fails (e.g. no network). Callers fall back to
    :func:`render_requirements_lock` so generation never depends on the
    network being reachable.
    """
    exe = shutil.which("pip-compile")
    if not exe:
        return None

    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "requirements.in"
        src.write_text("\n".join(DIRECT_DEPS) + "\n", encoding="utf-8")
        dst = Path(tmp) / "requirements.lock"
        try:
            proc = subprocess.run(
                [exe, "--quiet", "--output-file", str(dst), str(src)],
                capture_output=True, text=True, timeout=timeout, cwd=tmp,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        if proc.returncode != 0 or not dst.exists():
            return None
        pinned = dst.read_text(encoding="utf-8").strip("\n")
    if not pinned:
        return None
    return "\n".join([*_LOCK_HEADER, pinned, ""])
